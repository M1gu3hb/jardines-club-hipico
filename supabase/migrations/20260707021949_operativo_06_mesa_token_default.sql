-- Token automático para mesas nuevas (URL-safe, sin guiones).
alter table jardines.mesas
  alter column token set default replace(gen_random_uuid()::text, '-', '');
-- Backfill por si quedó alguna sin token.
update jardines.mesas set token = replace(gen_random_uuid()::text, '-', '') where token is null;;
